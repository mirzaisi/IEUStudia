def test_due_today_and_twenty_new_cards_a_day(env, monkeypatch):
    fake = [{"id": f"x{i}", "q": f"q{i}", "a": "a", "origin": "lecture", "source": {"day_key": "d"}, "week": 1,
             "stressed": False} for i in range(30)]
    s = cards.summary(env.lib, fake, "c", NOW)
    assert (s["total"], s["due"], s["new"], s["today"]) == (30, 0, 20, 20)
    for c in fake[:5]:
        cards.grade(env.lib, "c", c["id"], "good", NOW)                     # in learning: due in 10 minutes
    cards.grade(env.lib, "c", "x5", "easy", NOW)                            # learnt: due in 4 days
    s = cards.summary(env.lib, fake, "c", NOW)
    assert (s["due"], s["new"], s["reviewed_today"], s["learnt"]) == (5, 14, 6, 1)
    later = cards.session(env.lib, fake, "c", NOW + dt.timedelta(minutes=11))
    assert [c["id"] for c in later[:5]] == ["x0", "x1", "x2", "x3", "x4"] and len(later) == 5 + 14
    assert later[0]["state"]["step"] == 1 and set(later[0]["next"]) == set(cards.GRADES)
    tomorrow = cards.summary(env.lib, fake, "c", NOW + dt.timedelta(days=1))
    assert tomorrow["new"] == 20 and tomorrow["due"] == 5                    # the learning ones are still due


def test_a_sitting_past_midnight_is_still_the_evenings(env):
    """Today runs from 04:00 to 04:00: after midnight the evening's new cards, reviews and what is due still count, so
    a sitting from 23:30 to 00:30 gets 20 new cards, not 40, and the cards learnt in it wait for the morning."""
    fake = [{"id": f"x{i}", "q": f"q{i}", "a": "a", "origin": "lecture", "source": {"day_key": "d"}, "week": 1,
             "stressed": False} for i in range(30)]
    evening = dt.datetime(2026, 11, 9, 23, 30)
    for c in fake[:19]:
        cards.grade(env.lib, "c", c["id"], "good", evening)                 # in learning: back at 23:40
    cards.grade(env.lib, "c", "x19", "easy", evening)                        # learnt: 4 days
    cards.grade(env.lib, "c", "x0", "good", evening + dt.timedelta(minutes=20))   # learnt at 23:50: due at 04:00
    late = dt.datetime(2026, 11, 10, 0, 30)
    s = cards.summary(env.lib, fake, "c", late)
    assert (s["new"], s["reviewed_today"], s["due"]) == (0, 21, 18)
    assert [c["id"] for c in cards.session(env.lib, fake, "c", late)] == [f"x{i}" for i in range(1, 19)]
    morning = cards.summary(env.lib, fake, "c", dt.datetime(2026, 11, 10, 4, 0))
    assert (morning["new"], morning["reviewed_today"], morning["due"]) == (10, 0, 19)


def test_each_profile_keeps_its_own_reviews(tmp_path):
    """Two students on one PC: what one of them reviews is in their profile's library only (not the page's
    storage, which every profile shares)."""
    a, b = Library(tmp_path / "a.db"), Library(tmp_path / "b.db")
