def wait_done(lib, pid, timeout=10):
    t0 = time.monotonic()
    while time.monotonic() - t0 < timeout:
        p = lib.plan_brief(pid)
        if p["status"] in ("done", "error", "paused"):
            return p
        time.sleep(0.02)
    raise AssertionError("did not finish")


def test_cards_from_files_with_a_fake_ai(env):
    env.lib.set_material_file("r1", str(env.tmp / "Week01.pdf"), 10, "u")
    (env.tmp / "Week01.pdf").write_bytes(b"%PDF")
    env.lib.set_material_text("r1", ["Bayes theorem lets you turn a conditional probability around: P(B|A) from P(A|B).",
                                     "Title page",
                                     "Total probability: P(A) is the sum over the cases of P(A|B_i)P(B_i) for a partition."])
    asked = []

    def ask_text(system, content, model="sonnet", effort="low", cancel=None, on_text=None):
        asked.append(content[0]["text"])
        return {"text": json.dumps({"cards": [
            {"front": "What does Bayes' theorem do?", "back": "Turns $P(A|B)$ into $P(B|A)$.", "source": "F1 p.1"},
            {"front": "What is $P(A\\mid B)$?", "back": "Already in the deck", "source": "F1 p.1"},
            {"front": "State the total probability rule.", "back": "$P(A)=\\sum_i P(A|B_i)P(B_i)$"}]}),
            "usage": {"input_tokens": 10, "output_tokens": 5}, "model": model}

    runner = PlanRunner(env.svc, ask_text=ask_text)
    pid = runner.create("c", {"kind": "cards", "weeks": [1], "files": ["r1"], "picked": True})
    runner.start(pid)
    p = wait_done(env.lib, pid)
    assert p["status"] == "done", p
    assert len(asked) == 1 and "[F1 p.1] Bayes theorem" in asked[0] and "Title page" not in asked[0]
    assert "What is $P(A\\mid B)$?" in asked[0]                    # the cards the deck has: not repeated
    r = env.lib.plan(pid)["result"]
    assert [c["q"] for c in r["cards"]] == ["What does Bayes' theorem do?", "State the total probability rule."]
    assert r["cards"][0]["source"]["page"] == 1 and not r["cards"][0]["found"]
    assert r["cards"][1]["source"]["page"] == 3 and r["cards"][1]["found"]          # found by its words
    assert r["title"] == "Cards from Week01.pdf"
    deck = cards.deck(env.svc, "c")
    assert len(deck) == 4 and {c["origin"] for c in deck} == {"lecture", "files"}


