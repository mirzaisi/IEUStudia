# ------------------------------------------------------------------ scheduling
def test_a_new_card_learns_in_steps_then_graduates():
    s = cards.schedule(None, "good", NOW)
    assert s["step"] == 1 and s["due"] == "2026-11-09T10:10:00"             # 10 minutes
    s = cards.schedule(s, "good", NOW + dt.timedelta(minutes=10))
    assert s["step"] == -1 and s["interval"] == 1 and s["due"] == "2026-11-10T04:00:00"    # the next study day
    again = cards.schedule(None, "again", NOW)
    assert again["step"] == 0 and again["due"] == "2026-11-09T10:01:00"
    easy = cards.schedule(None, "easy", NOW)
    assert easy["step"] == -1 and easy["interval"] == 4 and easy["due"].startswith("2026-11-13")
    hard = cards.schedule(None, "hard", NOW)
    assert hard["step"] == 0 and hard["due"] == "2026-11-09T10:05:30"
    assert cards.schedule(None, "good", NOW)["first"] == NOW.isoformat(timespec="seconds")
    with pytest.raises(ValueError):
        cards.schedule(None, "maybe", NOW)


def test_a_learnt_card_is_spaced_out_by_its_ease_and_relearnt_when_forgotten():
    learnt = {"interval": 10.0, "ease": 2.5, "reps": 5, "lapses": 0, "step": -1, "relearn": False, "first": "x"}
    good = cards.schedule(learnt, "good", NOW)
    assert good["interval"] == 25 and good["due"].startswith("2026-12-04")
    hard = cards.schedule(learnt, "hard", NOW)
    assert hard["interval"] == 12 and hard["ease"] == 2.35
    easy = cards.schedule(learnt, "easy", NOW)
    assert easy["interval"] == pytest.approx(32.5) and easy["ease"] == 2.65
    lapse = cards.schedule(learnt, "again", NOW)
    assert (lapse["step"], lapse["relearn"], lapse["lapses"], lapse["interval"]) == (0, True, 1, 5)
    assert lapse["ease"] == 2.3 and lapse["due"] == "2026-11-09T10:10:00"
    back = cards.schedule(lapse, "good", NOW + dt.timedelta(minutes=10))
    assert back["step"] == -1 and back["interval"] == 5 and not back["relearn"]
    low = {**learnt, "ease": 1.35}
    assert cards.schedule(low, "again", NOW)["ease"] == 1.3                  # never below 1.3
    assert cards.schedule({**learnt, "interval": 300}, "easy", NOW)["interval"] == 365
    p = cards.preview(None, NOW)
    assert p == {"again": 60, "hard": 330, "good": 600, "easy": 4 * 86400}                  # "4 days"


def test_a_study_day_runs_from_four_in_the_morning():
    """As Anki counts days: a card learnt late in the evening comes back the next day, not at midnight minutes later,
    and its button says "1 day"."""
    night = dt.datetime(2026, 11, 9, 23, 40)
    s = cards.schedule(None, "good", night)                                  # back at 23:50
    learnt = night + dt.timedelta(minutes=10)
    assert cards.preview(s, learnt)["good"] == 86400
    s = cards.schedule(s, "good", learnt)
    assert s["step"] == -1 and s["due"] == "2026-11-10T04:00:00"
    assert cards.study_day(dt.datetime(2026, 11, 10, 1, 30)) == (dt.datetime(2026, 11, 9, 4), dt.datetime(2026, 11, 10, 4))
    assert cards.schedule(None, "easy", dt.datetime(2026, 11, 10, 1, 30))["due"] == "2026-11-13T04:00:00"   # the 9th's + 4
    assert cards.schedule(None, "easy", dt.datetime(2026, 11, 10, 4, 0))["due"] == "2026-11-14T04:00:00"


# ------------------------------------------------------------------ the deck
def lecture(lib, cid, did, when, lines):
    rec = Recording(delivery_id=did, course_id=cid, folder_id="f", folder_path="", name="n", start=when,
                    duration_s=4000, viewer_url="v")
    lib.merge_recordings(cid, [rec], first_sync=not lib.has_recordings(cid))
    segs = [Segment(i * 30.0, i * 30.0 + 4, text, "en", 0.9) for i, text in enumerate(lines)]
    tr = Transcript(delivery_id=did, segments=segs, duration_s=4000, speech_s=10, language_seconds={"en": 10},
                    model="m", device="cpu", engine_version="t", created_at="2026-10-01T12:00:00")
    lib.save_transcript(tr, store.save_transcript(tr))
    lib.set_status(did, "done")
    return lib.get_recording(did).day_key


