def _api(env, picked):
    from studia.api import Api

    a = Api.__new__(Api)
    a._services = env.s
    a._ready = __import__("threading").Event()
    a._ready.set()
    pushed = []
    a._push = pushed.append
    asked = []

    def dialog(folder, name, ext):
        asked.append((folder, name, ext))
        return picked
    a._save_dialog = dialog
    return a, asked, pushed


def test_the_api_asks_where_then_saves_and_remembers_the_format(env, monkeypatch):
    opened = []
    monkeypatch.setattr("studia.api.open_path", lambda p: opened.append(("open", p)))
    monkeypatch.setattr("studia.api.reveal", lambda p: opened.append(("show", p)))
    a, asked, _ = _api(env, "")
    assert a.export_pick(f"day:{env.day}", "transcript", "docx") == {"ok": True, "token": ""}       # cancelled
    assert asked == [(env.folder, "MATH 240 - 2026-09-23 Wed - Lecture - Transcript.docx", ".docx")]
