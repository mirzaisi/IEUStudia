def png(path: Path, w: int = 40, h: int = 30) -> str:
    """A real (tiny) PNG picture."""
    def chunk(kind: bytes, data: bytes) -> bytes:
        return struct.pack(">I", len(data)) + kind + data + struct.pack(">I", zlib.crc32(kind + data) & 0xFFFFFFFF)

    raw = b"".join(b"\x00" + b"\xff\x80\x00" * w for _ in range(h))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
                     + chunk(b"IDAT", zlib.compress(raw)) + chunk(b"IEND", b""))
    return str(path)


def _transcribe(lib, rec, texts):
    segs = [Segment(i * 30.0, i * 30.0 + 25, x, "tr" if re.search("[ğşı]", x) else "en", 0.9) for i, x in enumerate(texts)]
    tr = Transcript(delivery_id=rec.delivery_id, segments=segs, duration_s=rec.duration_s, speech_s=60,
                    language_seconds={}, model="large-v3-turbo", device="cuda", engine_version="t",
                    created_at="2026-10-01T12:00:00")
    lib.save_transcript(tr, store.save_transcript(tr))
    lib.set_status(rec.delivery_id, "done")


