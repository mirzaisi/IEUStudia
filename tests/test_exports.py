def parts_of(data: bytes) -> dict[str, bytes]:
    with zipfile.ZipFile(__import__("io").BytesIO(data)) as z:
        return {n: z.read(n) for n in z.namelist()}


# ------------------------------------------------------------------ the Word package
def check_docx(data: bytes) -> ET.Element:
    """Everything Word and LibreOffice need, as the standard has it; the document's XML."""
    parts = parts_of(data)
    names = list(parts)
    assert names[0] == "[Content_Types].xml"
    for need in ("_rels/.rels", "word/document.xml", "word/_rels/document.xml.rels", "word/styles.xml",
                 "word/numbering.xml", "word/settings.xml", "word/footer1.xml", "docProps/core.xml", "docProps/app.xml"):
        assert need in parts, need
    xml = {n: ET.fromstring(b) for n, b in parts.items() if n.endswith((".xml", ".rels"))}     # each one parses
    ct = xml["[Content_Types].xml"]
    defaults = {e.get("Extension") for e in ct if e.tag.endswith("Default")}
    overrides = {e.get("PartName") for e in ct if e.tag.endswith("Override")}
    for n in names:                                      # every part has its content type
        assert f"/{n}" in overrides or n.rsplit(".", 1)[-1] in defaults, n
    assert {"/word/document.xml", "/word/styles.xml", "/word/numbering.xml"} <= overrides
    root_rels = {r.get("Target") for r in xml["_rels/.rels"]}
    assert {"word/document.xml", "docProps/core.xml", "docProps/app.xml"} <= root_rels
    rels = {r.get("Id"): r for r in xml["word/_rels/document.xml.rels"]}
    assert len(rels) == len(list(xml["word/_rels/document.xml.rels"]))          # ids unique
    for r in rels.values():
        if r.get("TargetMode") == "External":
            assert r.get("Type").endswith("/hyperlink") and r.get("Target").startswith("https://")
        else:
            assert f"word/{r.get('Target')}" in parts, r.get("Target")
    document = xml["word/document.xml"]
    assert document.tag == f"{W}document"
    body = document.find(f"{W}body")
    assert body[-1].tag == f"{W}sectPr" and body[-2].tag == f"{W}p"
    used = {e.get(f"{R}id") for e in document.iter() if e.get(f"{R}id")}
    used |= {e.get(f"{R}embed") for e in document.iter() if e.get(f"{R}embed")}
    assert used <= set(rels), used - set(rels)
    for tc in document.iter(f"{W}tc"):
        assert tc.find(f"{W}p") is not None              # Word refuses a table cell without a paragraph
    styles = {s.get(f"{W}styleId") for s in xml["word/styles.xml"].iter(f"{W}style")}
    for tag in ("pStyle", "rStyle", "tblStyle"):
        for e in document.iter(f"{W}{tag}"):
            assert e.get(f"{W}val") in styles, e.get(f"{W}val")
    nums = {n.get(f"{W}numId") for n in xml["word/numbering.xml"].iter(f"{W}num")}
    for e in document.iter(f"{W}numId"):
        assert e.get(f"{W}val") in nums
    ids = [e.get("id") for e in document.iter("{http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing}docPr")]
    assert len(ids) == len(set(ids))
    for e in document.iter(f"{W}t"):                     # text with spaces at its ends keeps them
        if e.text and e.text != e.text.strip():
            assert e.get("{http://www.w3.org/XML/1998/namespace}space") == "preserve"
    return document


def text_of(document: ET.Element) -> str:
    return "\n".join("".join(t.text or "" for t in p.iter(f"{W}t")) for p in document.iter(f"{W}p"))


