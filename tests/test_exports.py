SEGS = [Segment(0, 5, "So good morning everyone.", "en", 0.9), Segment(4.8, 5.0, "Ok.", "en", 0.9),
        Segment(5.6, 30, " ".join(["word"] * 60), "en", 0.9), Segment(3700, 3702.5, "Bu & <şu> --> o.", "tr", 0.9),
        Segment(3703, 3703, "  ", "en", 0.9)]


def test_subtitles_have_their_times_in_order_and_never_overlap():
    cs = cues(SEGS)
    assert all(a < b for a, b, _ in cs)
    assert all(b <= cs[i + 1][0] for i, (_, b, _) in enumerate(cs[:-1]))     # one cue at a time
    assert cs[0][:2] == (0, 4.8)                       # cut where the next begins
    assert cs[1][1] == pytest.approx(5.3)              # a short one stays half a second when there is room
    assert all(b - a <= 7.01 for a, b, _ in cs[2:-1])   # a long segment in pieces of at most 7 s
    assert all(len(text.split("\n")) <= 2 for _, _, text in cs)
    srt = render_srt(SEGS)
    assert srt.startswith("1\n00:00:00,000 --> 00:00:04,800\nSo good morning everyone.\n\n2\n00:00:04,800 --> ")
    assert "01:01:40,000 --> 01:01:42,500\n[TR] Bu & <şu> --> o." in srt
    vtt = render_vtt(SEGS)
    assert vtt.startswith("WEBVTT\n\n1\n00:00:00.000 --> 00:00:04.800\nSo good morning everyone.\n")
    assert "01:01:40.000 --> 01:01:42.500\n[TR] Bu &amp; &lt;şu&gt; --&gt; o." in vtt
    assert len(re.findall(r"-->", vtt)) == len(cs)


